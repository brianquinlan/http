# Vendors the sources of libcurl and its dependencies into `third_party/`.
#
# Usage: ./tool/vendor_third_party.sh
#
# Each dependency is downloaded from a pinned source archive, verified against
# its SHA-256 hash and then only the files needed to build the libraries are
# copied into `third_party/<name>/`. To update a dependency, change its version
# and hash below and rerun this script.
#
# Requires: curl, tar, shasum (or sha256sum) and python3.

set -euo pipefail

DIR="$( cd "$( dirname "${BASH_SOURCE[0]}" )" >/dev/null 2>&1 && pwd )"
ROOT="$DIR/.."
THIRD_PARTY="$ROOT/third_party"

CURL_VERSION='8.23.0'
CURL_URL='https://codeload.github.com/curl/curl/tar.gz/refs/tags/curl-8_23_0'
CURL_SHA256='d0605d5883124ef5ae64c6d2b307e1417c482b362583b57491fdf37d9a99a792'

NGHTTP2_VERSION='1.70.0'
NGHTTP2_URL='https://codeload.github.com/nghttp2/nghttp2/tar.gz/refs/tags/v1.70.0'
NGHTTP2_SHA256='d38d641fb3877b4847c774ad88b5f3ab70daf1ae0e616079bbeec4691186fc6a'

# BoringSSL 0.20261020.0 and later declare `ASN1_STRING_get_length`, which
# conflicts with a static function of the same name in curl 8.23.0's
# `lib/vtls/openssl.c` (renamed to `ossl_ASN1_STRING_get_length` in later
# versions of curl).
BORINGSSL_VERSION='0.20260929.0'
BORINGSSL_URL='https://codeload.github.com/google/boringssl/tar.gz/refs/tags/0.20260929.0'
BORINGSSL_SHA256='04da9ba0664e0a7f028e961c38d604f2cc6dac852a84ca0e51dc1fa051d4c8fe'

log_info() {
    echo "[info] $1"
}

sha256() {
    if command -v sha256sum >/dev/null 2>&1; then
        sha256sum "$1" | awk '{print $1}'
    else
        shasum -a 256 "$1" | awk '{print $1}'
    fi
}

# download <url> <sha256> <destination-file>
download() {
    local url="$1"
    local expected="$2"
    local dest="$3"
    log_info "Downloading $url"
    curl -fsSL -o "$dest" "$url"
    local actual
    actual=$(sha256 "$dest")
    if [[ "$actual" != "$expected" ]]; then
        echo "[error] SHA-256 mismatch for $url" >&2
        echo "[error]   expected: $expected" >&2
        echo "[error]   actual:   $actual" >&2
        exit 1
    fi
}

# extract <archive> <destination-directory>
#
# Extracts the archive, stripping the top-level directory.
extract() {
    mkdir -p "$2"
    tar -xzf "$1" -C "$2" --strip-components=1
}

# copy_paths <source-root> <destination-root> <path>...
copy_paths() {
    local src="$1"
    local dst="$2"
    shift 2
    for path in "$@"; do
        mkdir -p "$(dirname "$dst/$path")"
        cp -R "$src/$path" "$dst/$path"
    done
}

# write_version_file <directory> <name> <version> <url> <sha256>
write_version_file() {
    cat > "$1/VENDORED.md" <<EOF
# $2 $3

**GENERATED FOLDER DO NOT MODIFY**

This folder contains a subset of the sources of $2 $3, which
\`package:curl_http\` compiles and bundles. Only the files required to build the
library are retained. It was generated by \`tool/vendor_third_party.sh\` from:

* URL: $4
* SHA-256: $5

Files in this folder are subject to the license of the $2 project, which is
included in this folder.
EOF
}

vendor_curl() {
    local tmp="$1"
    local archive="$tmp/curl.tar.gz"
    local src="$tmp/curl"
    local dst="$THIRD_PARTY/curl"

    download "$CURL_URL" "$CURL_SHA256" "$archive"
    extract "$archive" "$src"

    rm -rf "$dst"
    mkdir -p "$dst"
    copy_paths "$src" "$dst" \
        CMakeLists.txt \
        CMake \
        COPYING \
        curl-config.in \
        include \
        lib \
        libcurl.pc.in \
        scripts/CMakeLists.txt
    # Not needed to build libcurl.
    rm -f "$dst/lib/Makefile.am" "$dst/lib/Makefile.soname" \
        "$dst/include/Makefile.am" "$dst/include/curl/Makefile.am"
    write_version_file "$dst" curl "$CURL_VERSION" "$CURL_URL" "$CURL_SHA256"
}

vendor_nghttp2() {
    local tmp="$1"
    local archive="$tmp/nghttp2.tar.gz"
    local src="$tmp/nghttp2"
    local dst="$THIRD_PARTY/nghttp2"

    download "$NGHTTP2_URL" "$NGHTTP2_SHA256" "$archive"
    extract "$archive" "$src"

    rm -rf "$dst"
    mkdir -p "$dst/lib/includes/nghttp2"
    cp "$src/COPYING" "$dst/"
    cp "$src"/lib/*.c "$src"/lib/*.h "$dst/lib/"
    cp "$src/lib/includes/nghttp2/nghttp2.h" \
        "$src/lib/includes/nghttp2/nghttp2ver.h.in" \
        "$dst/lib/includes/nghttp2/"
    write_version_file "$dst" nghttp2 "$NGHTTP2_VERSION" "$NGHTTP2_URL" \
        "$NGHTTP2_SHA256"
}

vendor_boringssl() {
    local tmp="$1"
    local archive="$tmp/boringssl.tar.gz"
    local src="$tmp/boringssl"
    local dst="$THIRD_PARTY/boringssl"

    download "$BORINGSSL_URL" "$BORINGSSL_SHA256" "$archive"
    extract "$archive" "$src"

    rm -rf "$dst"
    mkdir -p "$dst"
    copy_paths "$src" "$dst" LICENSE include gen/sources.cmake

    # Copy the sources of libcrypto (including the FIPS module, "bcm") and
    # libssl that are listed in BoringSSL's generated build metadata.
    python3 - "$src" "$dst" <<'PY'
import json
import os
import shutil
import sys

src, dst = sys.argv[1:]
with open(os.path.join(src, 'gen', 'sources.json'), encoding='utf-8') as f:
    sources = json.load(f)

files = set()
for group in ('bcm', 'crypto', 'ssl'):
    for kind, paths in sources[group].items():
        files.update(paths)

for path in sorted(files):
    target = os.path.join(dst, path)
    os.makedirs(os.path.dirname(target), exist_ok=True)
    shutil.copy2(os.path.join(src, path), target)
print(f'[info] Copied {len(files)} BoringSSL files')
PY
    write_version_file "$dst" BoringSSL "$BORINGSSL_VERSION" "$BORINGSSL_URL" \
        "$BORINGSSL_SHA256"
}

main() {
    local tmp
    tmp=$(mktemp -d)
    # Expand $tmp now: the trap runs after `main` returns.
    # shellcheck disable=SC2064
    trap "rm -rf '$tmp'" EXIT

    mkdir -p "$THIRD_PARTY"
    vendor_curl "$tmp"
    vendor_nghttp2 "$tmp"
    vendor_boringssl "$tmp"

    log_info "Vendored sources:"
    du -sh "$THIRD_PARTY"/*
}

main "$@"
